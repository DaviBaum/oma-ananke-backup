@pytest.mark.parametrize("fault", ["prior_count", "missing_new", "boolean_count", "boolean_total", "wrong_total", "over_budget", "incomplete", "stale_budget", "phantom_contract", "duplicate_route"])
def test_zero_budget_requires_exact_new_native_component_count_inventory(fault):
    case = make_case("physical_route_set", budget=0, prior=True)
    witness = next(r["witness"] for r in case["report"]["results"] if r["id"] == "joint-new-fitting-budget")
    if fault == "prior_count": witness["per_new_route"]["prior-a"] = 0
    if fault == "missing_new": witness["per_new_route"].pop("new-a")
    if fault == "boolean_count": witness["per_new_route"]["new-a"] = False
    if fault == "boolean_total": witness["count"] = False
    if fault == "wrong_total": witness["count"] = 1
    if fault == "over_budget": witness["count"] = witness["per_new_route"]["new-a"] = 1
    if fault == "incomplete": witness["count_complete"] = False
    if fault == "stale_budget": case["run"]["request"]["mission"].pop("max_new_fittings")
    if fault == "phantom_contract": case["state"]["derived_artifacts"]["routing_contracts"]["phantom"] = {}; rebind(case)
    if fault == "duplicate_route": case["state"]["routes"].append(copy.deepcopy(case["state"]["routes"][0])); rebind(case)
    with pytest.raises(IntegrityError): admit(case)


